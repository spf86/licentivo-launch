// Fixed interface copy is bundled with the application. DeepL is reserved for
// merchant-authored brand, product, plan, document, and policy content.
func builtInUIStrings(locale string) map[string]string {
	values := make(map[string]string, len(siteUIStrings))
	for key, value := range siteUIStrings {
		values[key] = value
	}
	for key, value := range builtInUICatalogs[canonicalLocale(locale)] {
		values[key] = value
	}
	return values
}

var builtInUICatalogs = map[string]map[string]string{
	"en":    siteUIStringsEN,
	"ja":    siteUIStringsJA,
	"ko":    siteUIStringsKO,
	"de":    siteUIStringsDE,
	"fr":    siteUIStringsFR,
	"es":    siteUIStringsES,
	"pt-BR": siteUIStringsPTBR,
	"it":    siteUIStringsIT,
	"ru":    siteUIStringsRU,
}

func localizedUICatalog(overrides map[string]string) map[string]string {
	values := make(map[string]string, len(siteUIStringsEN))
	for key, value := range siteUIStringsEN {
		values[key] = value
	}
	for key, value := range overrides {
		values[key] = value
	}
	return values
}

